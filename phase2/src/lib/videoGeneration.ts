import { randomUUID } from "crypto";
import path from "path";
import type { VideoLayout } from "@prisma/client";
import { prisma } from "@/lib/prisma";
import { ensureDir, mediaUrlToAbsolutePath } from "@/lib/storage";
import { planSegments, renderVideo, type Segment } from "@/lib/ffmpeg";
import { randomItem, shuffle } from "@/lib/api";
import { parseClipStarts } from "@/lib/library";

export class VideoGenerationError extends Error {
  constructor(message: string) {
    super(message);
    this.name = "VideoGenerationError";
  }
}

/** Without replacement when the pool is big enough; otherwise reshuffle and repeat. */
function pickSegments<T>(pool: T[], count: number): T[] {
  const picked: T[] = [];
  while (picked.length < count) picked.push(...shuffle(pool));
  return picked.slice(0, count);
}

/**
 * Renders a fresh 12s video from a style's pools and drops it into the
 * user's posts as a DRAFT post. Never reuses a previous render.
 */
export async function generateVideoPostForStyle(styleId: string, userId: string, layout: VideoLayout) {
  const style = await prisma.videoStyle.findFirst({
    where: { id: styleId, userId },
    include: {
      images: true,
      videoClips: true,
      audioClips: { include: { libraryItem: { select: { clipStarts: true } } } },
      captions: true,
    },
  });
  if (!style) throw new VideoGenerationError("Style not found");

  const isCompilation = style.kind === "VIDEO_COMPILATION";
  const poolSize = isCompilation ? style.videoClips.length : style.images.length;
  if (poolSize === 0) throw new VideoGenerationError("Upload at least one image/video clip before generating");
  const bucketId = await postsBucketId(userId, style.defaultBucketId);

  const { segmentCount, crossfadeSec } = planSegments(style.secondsPerImage, style.crossfadeSec);
  const segments: Segment[] = isCompilation
    ? pickSegments(style.videoClips, segmentCount).map((clip) => ({
        kind: "video" as const,
        path: mediaUrlToAbsolutePath(clip.url),
        durationSec: clip.durationSec,
      }))
    : pickSegments(style.images, segmentCount).map((image) => ({ kind: "image" as const, path: mediaUrlToAbsolutePath(image.url) }));

  const audio = style.audioClips.length ? randomItem(style.audioClips) : null;
  const selectedCaption = style.captions.length ? randomItem(style.captions) : null;
  const songTitle = audio ? audio.postCaption?.trim() || audio.filename.replace(/\.[^.]+$/, "") : null;
  // The song's chosen timestamps, if any; otherwise a random 12s is used.
  const clipStarts = parseClipStarts(audio?.libraryItem?.clipStarts);
  const audioStart = clipStarts.length ? randomItem(clipStarts) : null;

  const generated = await prisma.generatedVideo.create({ data: { videoStyleId: style.id, status: "GENERATING" } });
  const subdir = "generated/videos";
  const filename = `${randomUUID()}.mp4`;
  const outputPath = path.join(await ensureDir(subdir), filename);
  const videoUrl = `/media/${subdir}/${filename}`;

  try {
    await renderVideo({
      segments,
      crossfadeSec,
      layout,
      caption: selectedCaption?.text ?? null,
      // "Titles: On-Screen / Off-Screen"
      songTitle: style.titleOnScreen ? songTitle : null,
      audioPath: audio ? mediaUrlToAbsolutePath(audio.url) : null,
      audioStart,
      outputPath,
    });

    const post = await prisma.post.create({
      data: {
        bucketId,
        caption: selectedCaption?.text ?? `${style.name} video`,
        // "Titles: Caption / No Caption" — when on, the TikTok post caption is
        // the audio track's title; otherwise the post has no caption.
        title: style.titleAsCaption && songTitle ? songTitle : null,
        mediaNote: `Generated by Video Studio — ${style.name}`,
        videoUrl,
        status: "DRAFT",
      },
    });
    return await prisma.generatedVideo.update({
      where: { id: generated.id },
      data: { status: "READY", url: videoUrl, postId: post.id },
      include: { post: { include: { bucket: true } } },
    });
  } catch (err) {
    const message = err instanceof Error ? err.message : "Video generation failed";
    await prisma.generatedVideo.update({
      where: { id: generated.id },
      data: { status: "FAILED", error: message.slice(0, 1000) },
    });
    throw new VideoGenerationError(message);
  }
}

/**
 * Posts still belong to a Bucket in the schema, but buckets are no longer a
 * user-facing feature (see git tag buckets-v1): every post shows on the Posts
 * page. Use the template's old target bucket if it still exists, otherwise the
 * user's oldest bucket, otherwise create a hidden one.
 */
async function postsBucketId(userId: string, preferredId: string | null): Promise<string> {
  if (preferredId) {
    const preferred = await prisma.bucket.findFirst({ where: { id: preferredId, userId }, select: { id: true } });
    if (preferred) return preferred.id;
  }
  const existing = await prisma.bucket.findFirst({ where: { userId }, orderBy: { createdAt: "asc" }, select: { id: true } });
  if (existing) return existing.id;
  const created = await prisma.bucket.create({ data: { userId, name: "Videos" } });
  return created.id;
}
